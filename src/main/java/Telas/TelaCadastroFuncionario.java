    private void carregarSetores() {
        try {
            Controller.ControllerSetor controller = new Controller.ControllerSetor();
            java.util.List<Model.ModelSetor> lista = controller.listar();
            cbSetor.removeAllItems();
            for (Model.ModelSetor s : lista) {
                cbSetor.addItem(s.getIdSetor() + " - " + s.getNomeSetor());
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar setores: " + e.getMessage());
        }
    }

